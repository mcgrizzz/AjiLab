// Builds public/vendor/lucide-food.js: the food and kitchen icons a recipe or
// folder can wear, taken from Lucide (https://lucide.dev, ISC licence).
//
// The package is 7 MB for the few dozen icons used here, so it isn't a
// dependency; the output is committed. To change the set, edit ICONS and run:
//   npm pack lucide-static && tar xzf lucide-static-*.tgz
//   node scripts/build-food-icons.mjs package/icons
import fs from 'node:fs';
import path from 'node:path';

// In picker order: baking, sweets, savoury, produce, protein, drinks,
// ferments and the lab, the kitchen, occasions.
const ICONS = [
  'wheat', 'croissant', 'sandwich', 'pizza', 'cake', 'cake-slice', 'cupcake', 'cookie', 'donut', 'dessert',
  'ice-cream-cone', 'ice-cream-bowl', 'popsicle', 'candy', 'lollipop', 'candy-cane', 'popcorn',
  'soup', 'salad', 'hamburger', 'leafy-green', 'carrot', 'apple', 'cherry', 'citrus', 'grape', 'banana', 'bean', 'nut',
  'egg', 'egg-fried', 'milk', 'beef', 'ham', 'drumstick', 'bacon', 'bird', 'fish', 'shrimp', 'shell', 'snail',
  'coffee', 'cup-soda', 'beer', 'wine', 'martini', 'bottle-wine', 'glass-water', 'hop',
  'amphora', 'flask-conical', 'flask-round', 'test-tube', 'beaker', 'microscope', 'sprout', 'leaf', 'clover', 'flower',
  'cooking-pot', 'chef-hat', 'utensils', 'fork-knife', 'hand-platter', 'flame', 'snowflake', 'thermometer', 'timer', 'scale',
  'party-popper', 'gift', 'tree-pine', 'ghost', 'heart', 'star', 'sun', 'moon', 'house',
];

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/build-food-icons.mjs <lucide-static/icons dir>');
const pkg = JSON.parse(fs.readFileSync(path.join(dir, '..', 'package.json'), 'utf8'));
const icons = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  const inner = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!inner) throw new Error(`no <svg> in ${name}`);
  icons[name] = inner.replace(/\s*\n\s*/g, '').trim();
}
const out = `// Generated by scripts/build-food-icons.mjs from lucide-static ${pkg.version}. Don't edit.
// Lucide icons, ISC License, Copyright (c) Lucide Icons and Contributors (https://lucide.dev).
// Each value is the inside of a 24×24 stroked <svg>.
const LUCIDE_FOOD = ${JSON.stringify(icons, null, 0).replace(/","/g, '",\n  "').replace(/^\{"/, '{\n  "').replace(/"\}$/, '"\n}')};
`;
const target = new URL('../public/vendor/lucide-food.js', import.meta.url);
fs.writeFileSync(target, out);
console.log(`${ICONS.length} icons → public/vendor/lucide-food.js (${out.length} bytes)`);
